    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        if(getText1().equals("") || getText2().equals("")){
            JOptionPane.showMessageDialog(this, "Sistem ne moze da zapamti licencu.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        kontroler.konvertujFormuUODO();
        Signal signal = kontroler.pozivSO(Operacija.UbaciLicenca);
        if(signal==Signal.Dobro){
            JOptionPane.showMessageDialog(this, "Sistem je zapamtio licencu.");
            izbrisiText();
        }
        else JOptionPane.showMessageDialog(this, "Sistem ne moze da zapamti licencu.", "Error", JOptionPane.ERROR_MESSAGE);
    }//GEN-LAST:event_jButton1ActionPerformed

