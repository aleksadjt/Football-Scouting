    public void ucitaj(){
        kontroler = new KreirajKlubKontroler(this);
        popuniComboBox(kontroler.vratiSveX(Operacija.VratiListuSviLiga), jComboBox1);
        
        koordinator = Koordinator.uzmiInstancu();
        kontroler.kreirajPrazanKlub();
        Signal signal = kontroler.pozivSO(Operacija.KreirajKlub);
        if(signal==Signal.Dobro) JOptionPane.showMessageDialog(this,"Sistem je kreirao klub.");
        else {
            JOptionPane.showMessageDialog(this, "Sistem ne moze da kreira klub.", "Error", JOptionPane.ERROR_MESSAGE);
            koordinator.zatvoriFormu(this);
        }
    }

