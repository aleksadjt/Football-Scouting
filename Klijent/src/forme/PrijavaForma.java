    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        kontroler.konvertujFormuUODO();
        Signal signal = kontroler.pozivSO(Operacija.PrijaviSkaut);
        if (signal==Signal.Dobro){
            JOptionPane.showMessageDialog(this, "Korisnicko ime i sifra su ispravni.");
            try {
                koordinator.pokreniGlavnuFormu(kontroler.uzmiUlogovanogSkauta());
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Ne moze da se otvori glavna forma i meni", "Error", JOptionPane.ERROR_MESSAGE);
            }
            finally{koordinator.zatvoriFormu(this);}
        }
        else JOptionPane.showMessageDialog(this, "Korisnicko ime i sifra nisu ispravni", "Error", JOptionPane.ERROR_MESSAGE);
    }//GEN-LAST:event_jButton1ActionPerformed

